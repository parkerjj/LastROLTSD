-- 023_ke_commerce.sql
-- 商务订单、支付收件箱和权益贡献历史。时间为毫秒 epoch，金额为 CNY 分。
-- 财务记录保留，不随账号或关联记录级联删除。

CREATE TABLE commerce_customers (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  stripe_account_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  stripe_livemode TINYINT(1) NOT NULL,
  stripe_customer_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at BIGINT UNSIGNED NOT NULL,
  updated_at BIGINT UNSIGNED NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commerce_customers_owner (user_id, stripe_account_id, stripe_livemode),
  UNIQUE KEY uq_commerce_customers_stripe (stripe_account_id, stripe_livemode, stripe_customer_id),
  CONSTRAINT fk_commerce_customers_user FOREIGN KEY (user_id) REFERENCES auth_users (id) ON DELETE RESTRICT,
  CONSTRAINT chk_commerce_customers_livemode CHECK (stripe_livemode IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE commerce_quotes (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  pricing_version VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  input_snapshot JSON NOT NULL,
  preview_snapshot JSON NOT NULL,
  raw_total_cents BIGINT UNSIGNED NOT NULL,
  tier_total_cents BIGINT UNSIGNED NOT NULL,
  promo_total_cents BIGINT UNSIGNED NULL,
  selected_total_cents BIGINT UNSIGNED NOT NULL,
  discount_strategy VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  promotion_snapshot JSON NULL,
  created_at BIGINT UNSIGNED NOT NULL,
  expires_at BIGINT UNSIGNED NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commerce_quotes_id_user (id, user_id),
  INDEX idx_commerce_quotes_owner_created (user_id, created_at, id),
  INDEX idx_commerce_quotes_expiry (expires_at, id),
  CONSTRAINT fk_commerce_quotes_user FOREIGN KEY (user_id) REFERENCES auth_users (id) ON DELETE RESTRICT,
  CONSTRAINT chk_commerce_quotes_window CHECK (expires_at > created_at),
  CONSTRAINT chk_commerce_quotes_currency CHECK (currency = 'CNY'),
  CONSTRAINT chk_commerce_quotes_discount CHECK (discount_strategy IN ('term', 'promotion_code'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE commerce_orders (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  quote_id BIGINT UNSIGNED NOT NULL,
  stripe_account_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  stripe_livemode TINYINT(1) NOT NULL,
  currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  items_snapshot JSON NOT NULL,
  pricing_version VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  raw_total_cents BIGINT UNSIGNED NOT NULL,
  tier_total_cents BIGINT UNSIGNED NOT NULL,
  promo_total_cents BIGINT UNSIGNED NULL,
  paid_total_cents BIGINT UNSIGNED NOT NULL,
  discount_strategy VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  promotion_snapshot JSON NULL,
  preview_snapshot JSON NOT NULL,
  confirmation_idempotency_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  checkout_state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'creating',
  payment_state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'unpaid',
  fulfillment_state VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'pending',
  refund_state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'none',
  refund_snapshot_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  refund_sync_generation BIGINT UNSIGNED NOT NULL DEFAULT 0,
  refund_revision BIGINT UNSIGNED NOT NULL DEFAULT 0,
  applied_refund_revision BIGINT UNSIGNED NOT NULL DEFAULT 0,
  stripe_checkout_session_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  stripe_payment_intent_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  stripe_charge_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  checkout_expires_at BIGINT UNSIGNED NULL,
  paid_at BIGINT UNSIGNED NULL,
  fulfilled_at BIGINT UNSIGNED NULL,
  created_at BIGINT UNSIGNED NOT NULL,
  updated_at BIGINT UNSIGNED NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commerce_orders_quote (quote_id),
  UNIQUE KEY uq_commerce_orders_confirmation (user_id, confirmation_idempotency_key),
  UNIQUE KEY uq_commerce_orders_session (stripe_account_id, stripe_livemode, stripe_checkout_session_id),
  UNIQUE KEY uq_commerce_orders_payment_intent (stripe_account_id, stripe_livemode, stripe_payment_intent_id),
  UNIQUE KEY uq_commerce_orders_charge (stripe_account_id, stripe_livemode, stripe_charge_id),
  INDEX idx_commerce_orders_owner_created (user_id, created_at, id),
  INDEX idx_commerce_orders_owner_payment (user_id, payment_state, created_at, id),
  CONSTRAINT fk_commerce_orders_user FOREIGN KEY (user_id) REFERENCES auth_users (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commerce_orders_quote_owner FOREIGN KEY (quote_id, user_id) REFERENCES commerce_quotes (id, user_id) ON DELETE RESTRICT,
  CONSTRAINT chk_commerce_orders_livemode CHECK (stripe_livemode IN (0, 1)),
  CONSTRAINT chk_commerce_orders_currency CHECK (currency = 'CNY'),
  CONSTRAINT chk_commerce_orders_discount CHECK (discount_strategy IN ('term', 'promotion_code')),
  CONSTRAINT chk_commerce_orders_checkout CHECK (checkout_state IN ('creating', 'ready', 'failed', 'expired')),
  CONSTRAINT chk_commerce_orders_payment CHECK (payment_state IN ('unpaid', 'processing', 'paid')),
  CONSTRAINT chk_commerce_orders_fulfillment CHECK (fulfillment_state IN ('pending', 'fulfilled', 'settled')),
  CONSTRAINT chk_commerce_orders_refund CHECK (refund_state IN ('none', 'partial', 'full'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE commerce_units (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  resource VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  unit_kind VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  ke_entitlement_id BIGINT UNSIGNED NULL,
  baseline_source VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NULL,
  baseline_source_ref VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  baseline_quantity INT NOT NULL DEFAULT 0,
  baseline_starts_at BIGINT UNSIGNED NULL,
  baseline_expires_at BIGINT UNSIGNED NULL,
  legacy_origin_id BIGINT UNSIGNED NULL,
  legacy_ordinal INT UNSIGNED NULL,
  admin_revoked_at BIGINT UNSIGNED NULL,
  refund_zeroed_at BIGINT UNSIGNED NULL,
  created_at BIGINT UNSIGNED NOT NULL,
  updated_at BIGINT UNSIGNED NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commerce_units_entitlement (ke_entitlement_id),
  UNIQUE KEY uq_commerce_units_legacy_origin (legacy_origin_id, legacy_ordinal),
  INDEX idx_commerce_units_owner_resource (user_id, resource, id),
  CONSTRAINT fk_commerce_units_user FOREIGN KEY (user_id) REFERENCES auth_users (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commerce_units_entitlement FOREIGN KEY (ke_entitlement_id) REFERENCES ke_entitlements (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commerce_units_legacy_origin FOREIGN KEY (legacy_origin_id) REFERENCES ke_entitlements (id) ON DELETE RESTRICT,
  CONSTRAINT chk_commerce_units_kind CHECK (unit_kind IN ('commerce', 'legacy')),
  CONSTRAINT chk_commerce_units_baseline CHECK (baseline_quantity >= 0),
  CONSTRAINT chk_commerce_units_window CHECK (baseline_expires_at IS NULL OR baseline_starts_at IS NULL OR baseline_expires_at > baseline_starts_at),
  CONSTRAINT chk_commerce_units_legacy_pair CHECK ((legacy_origin_id IS NULL) = (legacy_ordinal IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE commerce_order_items (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  order_id BIGINT UNSIGNED NOT NULL,
  ordinal SMALLINT UNSIGNED NOT NULL,
  product_key VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  resource VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  operation VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  target_unit_id BIGINT UNSIGNED NULL,
  target_entitlement_id BIGINT UNSIGNED NULL,
  target_ref VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
  duration_ms BIGINT UNSIGNED NOT NULL,
  raw_cents BIGINT UNSIGNED NOT NULL,
  tier_percent TINYINT UNSIGNED NOT NULL,
  tier_cents BIGINT UNSIGNED NOT NULL,
  paid_cents BIGINT UNSIGNED NOT NULL,
  expected_starts_at BIGINT UNSIGNED NOT NULL,
  expected_expires_at BIGINT UNSIGNED NOT NULL,
  delivery_state VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'pending',
  delivered_at BIGINT UNSIGNED NULL,
  created_at BIGINT UNSIGNED NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commerce_order_items_ordinal (order_id, ordinal),
  INDEX idx_commerce_order_items_target (target_unit_id, id),
  CONSTRAINT fk_commerce_order_items_order FOREIGN KEY (order_id) REFERENCES commerce_orders (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commerce_order_items_unit FOREIGN KEY (target_unit_id) REFERENCES commerce_units (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commerce_order_items_entitlement FOREIGN KEY (target_entitlement_id) REFERENCES ke_entitlements (id) ON DELETE RESTRICT,
  CONSTRAINT chk_commerce_order_items_product CHECK (product_key IN ('slots', 'module:standalone')),
  CONSTRAINT chk_commerce_order_items_operation CHECK (operation IN ('ADD', 'RENEW', 'ALIGN')),
  CONSTRAINT chk_commerce_order_items_tier CHECK (tier_percent IN (70, 80, 100)),
  CONSTRAINT chk_commerce_order_items_window CHECK (expected_expires_at > expected_starts_at),
  CONSTRAINT chk_commerce_order_items_delivery CHECK (delivery_state IN ('pending', 'delivered', 'settled_no_entitlement'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE commerce_unit_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  unit_id BIGINT UNSIGNED NOT NULL,
  unit_seq INT UNSIGNED NOT NULL,
  event_type VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  order_item_id BIGINT UNSIGNED NULL,
  refund_revision BIGINT UNSIGNED NULL,
  before_starts_at BIGINT UNSIGNED NULL,
  before_expires_at BIGINT UNSIGNED NULL,
  after_starts_at BIGINT UNSIGNED NULL,
  after_expires_at BIGINT UNSIGNED NULL,
  occurred_at BIGINT UNSIGNED NOT NULL,
  delivered_at BIGINT UNSIGNED NULL,
  duration_ms BIGINT NOT NULL DEFAULT 0,
  dedupe_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  detail_json JSON NULL,
  created_at BIGINT UNSIGNED NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commerce_unit_events_sequence (unit_id, unit_seq),
  UNIQUE KEY uq_commerce_unit_events_item_revision (order_item_id, refund_revision, event_type),
  UNIQUE KEY uq_commerce_unit_events_dedupe (dedupe_key),
  INDEX idx_commerce_unit_events_refund (unit_id, refund_revision),
  CONSTRAINT fk_commerce_unit_events_unit FOREIGN KEY (unit_id) REFERENCES commerce_units (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commerce_unit_events_item FOREIGN KEY (order_item_id) REFERENCES commerce_order_items (id) ON DELETE RESTRICT,
  CONSTRAINT chk_commerce_unit_events_type CHECK (event_type IN ('BASELINE', 'PURCHASE', 'ADMIN_DELTA', 'ADMIN_CUTOFF', 'ADMIN_REVOKE', 'ADMIN_RESTORE', 'REFUND_REPROJECT')),
  CONSTRAINT chk_commerce_unit_events_refund_revision CHECK (event_type <> 'REFUND_REPROJECT' OR refund_revision IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE commerce_refunds (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  order_id BIGINT UNSIGNED NOT NULL,
  stripe_account_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  stripe_livemode TINYINT(1) NOT NULL,
  stripe_refund_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  amount_cents BIGINT UNSIGNED NOT NULL,
  currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  stripe_created_at BIGINT UNSIGNED NULL,
  created_at BIGINT UNSIGNED NOT NULL,
  updated_at BIGINT UNSIGNED NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commerce_refunds_stripe (stripe_account_id, stripe_livemode, stripe_refund_id),
  INDEX idx_commerce_refunds_order (order_id, status, id),
  CONSTRAINT fk_commerce_refunds_order FOREIGN KEY (order_id) REFERENCES commerce_orders (id) ON DELETE RESTRICT,
  CONSTRAINT chk_commerce_refunds_livemode CHECK (stripe_livemode IN (0, 1)),
  CONSTRAINT chk_commerce_refunds_currency CHECK (currency = 'CNY'),
  CONSTRAINT chk_commerce_refunds_status CHECK (status IN ('pending', 'requires_action', 'succeeded', 'failed', 'canceled'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE commerce_provider_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  stripe_account_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  stripe_livemode TINYINT(1) NOT NULL,
  stripe_event_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  event_type VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  object_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  order_id BIGINT UNSIGNED NULL,
  payload_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'received',
  received_at BIGINT UNSIGNED NOT NULL,
  processed_at BIGINT UNSIGNED NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commerce_provider_events_stripe (stripe_account_id, stripe_livemode, stripe_event_id),
  INDEX idx_commerce_provider_events_order (order_id, received_at, id),
  CONSTRAINT fk_commerce_provider_events_order FOREIGN KEY (order_id) REFERENCES commerce_orders (id) ON DELETE RESTRICT,
  CONSTRAINT chk_commerce_provider_events_livemode CHECK (stripe_livemode IN (0, 1)),
  CONSTRAINT chk_commerce_provider_events_state CHECK (state IN ('received', 'queued', 'processed', 'ignored'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE commerce_jobs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  job_key VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  job_type VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  order_id BIGINT UNSIGNED NOT NULL,
  state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'queued',
  dirty_generation BIGINT UNSIGNED NOT NULL DEFAULT 1,
  processed_generation BIGINT UNSIGNED NOT NULL DEFAULT 0,
  next_run_at BIGINT UNSIGNED NOT NULL,
  lease_owner VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  lease_until BIGINT UNSIGNED NULL,
  fencing_token BIGINT UNSIGNED NOT NULL DEFAULT 0,
  attempts INT UNSIGNED NOT NULL DEFAULT 0,
  last_error_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  cursor_json JSON NULL,
  created_at BIGINT UNSIGNED NOT NULL,
  updated_at BIGINT UNSIGNED NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commerce_jobs_key (job_key),
  UNIQUE KEY uq_commerce_jobs_order_type (job_type, order_id),
  INDEX idx_commerce_jobs_due (state, next_run_at, lease_until, id),
  INDEX idx_commerce_jobs_lease (lease_until, id),
  CONSTRAINT fk_commerce_jobs_order FOREIGN KEY (order_id) REFERENCES commerce_orders (id) ON DELETE RESTRICT,
  CONSTRAINT chk_commerce_jobs_type CHECK (job_type IN ('order_reconcile')),
  CONSTRAINT chk_commerce_jobs_state CHECK (state IN ('queued', 'leased', 'failed', 'done')),
  CONSTRAINT chk_commerce_jobs_generation CHECK (processed_generation <= dirty_generation),
  CONSTRAINT chk_commerce_jobs_lease_pair CHECK ((lease_owner IS NULL) = (lease_until IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
