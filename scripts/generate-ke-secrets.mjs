// 生成 KoreEngine 授权所需的密钥材料（命令行，一次性）。
//   node scripts/generate-ke-secrets.mjs [--output-dir <目录>] [--force]
// 默认写入仓库根目录下的 .ke-secrets.local/（已被 .gitignore 忽略，权限 0600/0700）。
//
// 产物：
//   ke-secrets.env          KE_LICENSE_PRIVATE_KEY_v1（Ed25519 私钥，PKCS8 DER base64）+ KE_CORE_KEY（K_core，AES-256 base64）
//                           —— 填入 GitHub Actions secrets / `wrangler secret put`，同时 K_core 供 KE 构建脚本加密 core.wasm
//   ke-license-public.txt   Ed25519 公钥（raw 32 字节：base64 与 hex）—— 非机密，烘焙进 KE 的 boot.wasm 用于验签
//
// 仅打印公钥与文件路径，私钥与 K_core 不会输出到终端或日志。
import { createPrivateKey, createPublicKey, randomBytes, generateKeyPairSync, sign, verify } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** 生成一套全新的 KE 密钥材料（不落盘）。编码与 Worker 的 resolveKeConfig 要求一致：标准 base64（带 = 填充）。 */
export function generateKeSecrets() {
  const { privateKey, publicKey } = generateKeyPairSync('ed25519');
  const pkcs8 = privateKey.export({ type: 'pkcs8', format: 'der' });
  const rawPublic = publicKey.export({ type: 'spki', format: 'der' }).subarray(-32);
  const coreKey = randomBytes(32);

  // 自检：长度、「落盘用的 DER 私钥」导出的公钥与公布的公钥一致、签名/验签闭环。
  if (pkcs8.byteLength !== 48 || rawPublic.byteLength !== 32) throw new Error('unexpected Ed25519 key length');
  const imported = createPrivateKey({ key: pkcs8, format: 'der', type: 'pkcs8' });
  const derivedPublic = createPublicKey(imported).export({ type: 'spki', format: 'der' }).subarray(-32);
  if (!derivedPublic.equals(rawPublic)) throw new Error('Ed25519 public/private key mismatch');
  const probe = Buffer.from('ke-license-selfcheck');
  if (!verify(null, probe, publicKey, sign(null, probe, imported))) throw new Error('Ed25519 self-check failed');

  return {
    licensePrivateKey: pkcs8.toString('base64'),
    licensePublicKeyBase64: rawPublic.toString('base64'),
    licensePublicKeyHex: rawPublic.toString('hex'),
    coreKey: coreKey.toString('base64'),
  };
}

export function renderSecretsEnv(secrets) {
  return [
    '# Generated by scripts/generate-ke-secrets.mjs. Do not commit, paste into logs, or send in chat.',
    '# KE_LICENSE_PRIVATE_KEY_v1: Ed25519 私钥（PKCS8 DER base64）。泄露 = 任何人可伪造 license，须立即轮换。',
    '# KE_CORE_KEY: K_core（AES-256）。KE 构建期用它加密 core.wasm；泄露 = core 块脱离 LTSD 控制，须 bump KE_CORE_KEY_VERSION 并重新构建。',
    `KE_LICENSE_PRIVATE_KEY_v1=${secrets.licensePrivateKey}`,
    'KE_LICENSE_KEY_VERSION=1',
    `KE_CORE_KEY=${secrets.coreKey}`,
    'KE_CORE_KEY_VERSION=1',
    '',
  ].join('\n');
}

export function renderPublicKey(secrets) {
  return [
    '# Ed25519 license 公钥（raw 32 字节）。非机密：烘焙进 KE 的 boot.wasm，用于验签 LTSD 签发的 license。',
    '# kid = ke-license-ed25519-v1（与 Worker 的 KE_LICENSE_KEY_VERSION=1 对应）',
    `base64: ${secrets.licensePublicKeyBase64}`,
    `hex:    ${secrets.licensePublicKeyHex}`,
    '',
  ].join('\n');
}

function optionValue(name, fallback) {
  const index = process.argv.indexOf(name);
  return index === -1 ? fallback : process.argv[index + 1];
}

function runCli() {
  const outputDir = resolve(optionValue('--output-dir', resolve(process.cwd(), '.ke-secrets.local')));
  const force = process.argv.includes('--force');
  const envPath = resolve(outputDir, 'ke-secrets.env');
  const publicPath = resolve(outputDir, 'ke-license-public.txt');

  for (const path of [envPath, publicPath]) {
    if (!force && existsSync(path)) {
      console.error(`${path} already exists; use --force only when rotating (rotation invalidates the previous KE build, see docs/ke-release.md).`);
      process.exit(1);
    }
  }

  const secrets = generateKeSecrets();
  mkdirSync(outputDir, { recursive: true, mode: 0o700 });
  writeFileSync(envPath, renderSecretsEnv(secrets), { encoding: 'utf8', mode: 0o600 });
  writeFileSync(publicPath, renderPublicKey(secrets), { encoding: 'utf8', mode: 0o600 });
  console.log(`Generated ${envPath} and ${publicPath}. Private key and K_core were not printed.`);
  console.log(`License public key (base64, safe to share): ${secrets.licensePublicKeyBase64}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) runCli();
